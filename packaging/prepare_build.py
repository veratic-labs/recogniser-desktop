"""Prepare the generated build inputs from the repository's own assets.

Run from the project root with:

    python packaging\\prepare_build.py

This validates ``packaging/version.txt``, writes ``build/version_info.txt`` for
the PyInstaller ``EXE(version=...)`` argument, and generates
``packaging/assets/recogniser.ico`` from ``images/icon.png`` when the ICO is
missing, stale, or when ``--force`` is given.

Nothing is downloaded, and nothing is written outside the project root.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

from PIL import Image

PROJECT_ROOT = Path(__file__).resolve().parents[1]
VERSION_FILE = PROJECT_ROOT / "packaging" / "version.txt"
VERSION_INFO_FILE = PROJECT_ROOT / "build" / "version_info.txt"
ICON_SOURCE = PROJECT_ROOT / "images" / "icon.png"
ICON_TARGET = PROJECT_ROOT / "packaging" / "assets" / "recogniser.ico"

# Both the executable's icon resource and the installer's shortcut icons use
# this file, so it must carry every size Windows asks for.
ICON_SIZES = (16, 24, 32, 48, 64, 128, 256)

VERSION_PATTERN = re.compile(r"^\d+\.\d+\.\d+$")

VERSION_INFO_TEMPLATE = """\
# Generated by packaging/prepare_build.py from packaging/version.txt.
# Do not edit: change packaging/version.txt and regenerate instead.
VSVersionInfo(
  ffi=FixedFileInfo(
    filevers={file_version},
    prodvers={file_version},
    mask=0x3f,
    flags=0x0,
    OS=0x40004,
    fileType=0x1,
    subtype=0x0,
    date=(0, 0)
  ),
  kids=[
    StringFileInfo([
      StringTable(
        '040904B0',
        [StringStruct('CompanyName', ''),
         StringStruct('FileDescription', 'recogniser'),
         StringStruct('FileVersion', '{version}'),
         StringStruct('InternalName', 'recogniser'),
         StringStruct('LegalCopyright', ''),
         StringStruct('OriginalFilename', 'recogniser.exe'),
         StringStruct('ProductName', 'recogniser'),
         StringStruct('ProductVersion', '{version}')])
    ]),
    VarFileInfo([VarStruct('Translation', [1033, 1200])])
  ]
)
"""


def read_version() -> str:
    """Return the validated three-part version from ``packaging/version.txt``."""
    if not VERSION_FILE.is_file():
        raise FileNotFoundError(f"The version file is missing: {VERSION_FILE}")

    version = VERSION_FILE.read_text(encoding="utf-8").strip()
    if not VERSION_PATTERN.match(version):
        raise ValueError(
            f"{VERSION_FILE} must contain a three-part version such as 1.0.0, "
            f"but it contains {version!r}."
        )
    return version


def four_part_version(version: str) -> tuple[int, int, int, int]:
    """Return the four-part tuple the Windows file version needs."""
    return (*[int(part) for part in version.split(".")], 0)


def write_version_info(version: str) -> Path:
    """Write ``build/version_info.txt`` and return its path."""
    VERSION_INFO_FILE.parent.mkdir(parents=True, exist_ok=True)
    VERSION_INFO_FILE.write_text(
        VERSION_INFO_TEMPLATE.format(
            version=version, file_version=four_part_version(version)
        ),
        encoding="utf-8",
    )
    return VERSION_INFO_FILE


def icon_is_stale() -> bool:
    """Return whether the ICO must be regenerated from the source PNG."""
    if not ICON_TARGET.is_file():
        return True
    return ICON_TARGET.stat().st_mtime < ICON_SOURCE.stat().st_mtime


def write_icon() -> Path:
    """Generate the multi-resolution ICO from ``images/icon.png``.

    Pillow writes every requested size and resizes each entry with LANCZOS.
    """
    if not ICON_SOURCE.is_file():
        raise FileNotFoundError(f"The icon source is missing: {ICON_SOURCE}")

    with Image.open(ICON_SOURCE) as source:
        image = source.convert("RGBA")
        largest = max(ICON_SIZES)
        if image.width < largest or image.height < largest:
            raise ValueError(
                f"{ICON_SOURCE} is {image.width} x {image.height}, but the ICO "
                f"needs at least {largest} x {largest}."
            )
        ICON_TARGET.parent.mkdir(parents=True, exist_ok=True)
        image.save(
            ICON_TARGET, format="ICO", sizes=[(size, size) for size in ICON_SIZES]
        )
    return ICON_TARGET


def icon_sizes(path: Path) -> set[tuple[int, int]]:
    """Return the entries an ICO file actually contains."""
    with Image.open(path) as icon:
        return set(icon.info.get("sizes", ()))


def main(argv: list[str] | None = None) -> int:
    """Prepare the generated build inputs and return an exit code."""
    arguments = list(sys.argv[1:] if argv is None else argv)

    version = read_version()
    info = write_version_info(version)
    file_version = ".".join(str(part) for part in four_part_version(version))
    print(f"Version: {version} (file version {file_version})")
    print(f"Version info: {info}")

    if "--force" in arguments or icon_is_stale():
        icon = write_icon()
        print(f"Icon written: {icon}")
    else:
        icon = ICON_TARGET
        print(f"Icon up to date: {icon}")

    missing = sorted(
        size for size in ICON_SIZES if (size, size) not in icon_sizes(icon)
    )
    if missing:
        print(f"Icon entries missing: {missing}")
        return 1
    print(f"Icon entries: {sorted(size for size, _ in icon_sizes(icon))}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
